def update_env_file(path: Path, values: dict[str, str]) -> None:
    unknown = set(values) - SAFE_SETUP_KEYS
    if unknown:
        raise ValueError(f"setup cannot write unsupported settings: {sorted(unknown)}")
    if any(any(character in value for character in "\r\n\0") for value in values.values()):
        raise ValueError("setup values cannot contain control characters")

    if path.is_symlink():
        raise ValueError("setup refuses to read or replace a symlinked environment file")
    existing = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    pending = dict(values)
    output: list[str] = []
    written: set[str] = set()
    for line in existing:
        key, separator, _ = line.partition("=")
        if separator and key in pending:
            if key not in written:
                output.append(f"{key}={pending[key]}")
                written.add(key)
            continue
        output.append(line)
    for key, value in pending.items():
        if key not in written:
            output.append(f"{key}={value}")

    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        dir=path.parent,
        prefix=f".{path.name}.",
        suffix=".tmp",
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write("\n".join(output).rstrip() + "\n")
        temporary.chmod(0o600)
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)
    path.chmod(0o600)


def snapshot_env_file(path: Path) -> bytes | None:
    """Capture a private env file so a coordinated database write can be undone."""
    if path.is_symlink():
        raise ValueError("setup refuses to read or replace a symlinked environment file")
    return path.read_bytes() if path.exists() else None


def restore_env_file(path: Path, snapshot: bytes | None) -> None:
    """Restore an env snapshot atomically after a related database failure."""
    if path.is_symlink():
        raise ValueError("setup refuses to read or replace a symlinked environment file")
    if snapshot is None:
        path.unlink(missing_ok=True)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        dir=path.parent,
        prefix=f".{path.name}.",
        suffix=".restore",
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(snapshot)
        temporary.chmod(0o600)
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)
    path.chmod(0o600)


def provider_settings(provider: ProviderName, model: str = "qwen3.5:9b") -> dict[str, str]:
    if not OLLAMA_MODEL_PATTERN.fullmatch(model):
        raise ValueError("Ollama model name contains unsupported characters")
    values = {"MODEL_PROVIDER": provider}
    if provider == "ollama":
        values.update(
            {
                "OLLAMA_BASE_URL": "http://127.0.0.1:11434",
                "OLLAMA_MODEL": model,
                "OLLAMA_ECONOMY_MODEL": model,
                "OLLAMA_BALANCED_MODEL": model,
                "OLLAMA_DEEP_MODEL": model,
                "OLLAMA_CONTEXT_LENGTH": "16384",
                "STARTUP_MODEL_SMOKE_TEST": "true",
                "LOCAL_SERVICE_AUTOSTART": "true",
            }
        )
    return values


def ollama_profile_settings(model: str, tier: OllamaTier) -> dict[str, str]:
    if not OLLAMA_MODEL_PATTERN.fullmatch(model):
        raise ValueError("Ollama model name contains unsupported characters")
    keys = {
        "default": ("OLLAMA_MODEL",),
        "economy": ("OLLAMA_ECONOMY_MODEL",),
        "balanced": ("OLLAMA_BALANCED_MODEL",),
        "deep": ("OLLAMA_DEEP_MODEL",),
        "quality": ("OLLAMA_BALANCED_MODEL", "OLLAMA_DEEP_MODEL"),
        "all": (
            "OLLAMA_MODEL",
            "OLLAMA_ECONOMY_MODEL",
            "OLLAMA_BALANCED_MODEL",
            "OLLAMA_DEEP_MODEL",
        ),
    }
    return {key: model for key in keys[tier]}


def operating_system() -> Literal["macos", "linux", "windows", "other"]:
    system = platform.system().lower()
    if system == "darwin":
        return "macos"
    if system == "linux":
        return "linux"
    if system == "windows":
        return "windows"
    return "other"


def launcher_target_for_interpreter(
    interpreter: Path,
    *,
    system: str | None = None,
) -> Path:
    resolved_system = system or operating_system()
    executable = "trade.exe" if resolved_system == "windows" else "trade"
    return interpreter.parent / executable


def install_user_launcher(
    target: Path,
    launcher_name: str = "trade",
    *,
    system: str | None = None,
) -> Path:
    if not target.is_file():
        raise FileNotFoundError(
            f"launcher target is not a regular file: {target}"
        )
    resolved_system = system or operating_system()
    if resolved_system == "windows":
        local_app_data = os.environ.get("LOCALAPPDATA")
        base = Path(local_app_data) if local_app_data else Path.home() / "AppData" / "Local"
        bin_directory = base / "TradingAgent" / "bin"
        bin_directory.mkdir(parents=True, exist_ok=True)
        launcher = bin_directory / f"{launcher_name}.cmd"
        if launcher.is_symlink():
            raise FileExistsError(f"refusing to replace existing symlink: {launcher}")
        if launcher.exists():
            existing = launcher.read_text(encoding="utf-8")
            if not existing.startswith(WINDOWS_LAUNCHER_MARKER):
                raise FileExistsError(f"refusing to replace existing file: {launcher}")
        escaped_target = str(target.resolve()).replace("%", "%%")
        descriptor, temporary_name = tempfile.mkstemp(
            dir=bin_directory,
            prefix=f".{launcher.name}.",
            suffix=".tmp",
        )
        temporary = Path(temporary_name)
        try:
            with os.fdopen(descriptor, "w", encoding="utf-8", newline="") as handle:
                handle.write(
                    f'{WINDOWS_LAUNCHER_MARKER}\r\n'
                    f'@echo off\r\n"{escaped_target}" %*\r\n'
                )
            temporary.replace(launcher)
        finally:
            temporary.unlink(missing_ok=True)
        return launcher

    bin_directory = Path.home() / ".local" / "bin"
    bin_directory.mkdir(parents=True, exist_ok=True)
    launcher = bin_directory / launcher_name
    if launcher.exists() and not launcher.is_symlink():
        raise FileExistsError(f"refusing to replace existing file: {launcher}")
    if launcher.is_symlink():
        launcher.unlink()
    launcher.symlink_to(target.resolve())
    return launcher


def _homebrew() -> str | None:
    return shutil.which("brew")


def start_homebrew_service(service_name: str) -> tuple[bool, str]:
    brew = _homebrew()
    if brew is None:
        return False, "Homebrew is not installed"
    result = subprocess.run(  # noqa: S603
        [brew, "services", "start", service_name],
        check=False,
        capture_output=True,
        text=True,
        timeout=120,
    )
    detail = (result.stdout or result.stderr).strip()
    return result.returncode == 0, detail[:500]


