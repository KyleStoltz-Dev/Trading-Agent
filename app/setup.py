def _start_background_ollama() -> tuple[bool, str]:
    ollama = shutil.which("ollama")
    if ollama is None:
        return False, dependency_guidance("ollama")
    popen_kwargs: dict[str, object] = {
        "stdin": subprocess.DEVNULL,
        "stdout": subprocess.DEVNULL,
        "stderr": subprocess.DEVNULL,
    }
    if operating_system() == "windows":
        popen_kwargs["creationflags"] = (
            subprocess.CREATE_NEW_PROCESS_GROUP | subprocess.DETACHED_PROCESS
        )
    else:
        popen_kwargs["start_new_session"] = True
    try:
        subprocess.Popen([ollama, "serve"], **popen_kwargs)  # noqa: S603
    except OSError as exc:
        return False, f"could not start `ollama serve`: {exc}"
    return True, "started `ollama serve` in the background"


def start_local_service(
    service: Literal["ollama", "postgresql"],
    *,
    postgres_service_name: str = "postgresql",
) -> tuple[bool, str]:
    if service == "ollama":
        if operating_system() == "macos" and _homebrew() is not None:
            ok, detail = start_homebrew_service("ollama")
            if ok:
                return ok, detail
        return _start_background_ollama()

    if operating_system() == "macos" and _homebrew() is not None:
        return start_homebrew_service(postgres_service_name)
    return False, dependency_guidance("postgresql")


def estimate_ollama_download_size(model: str) -> int | None:
    """Return a conservative byte estimate when a parameter count is in the tag."""
    match = OLLAMA_PARAMETER_COUNT.search(model)
    if match is None:
        return None
    parameters_billions = float(match.group(1))
    if parameters_billions <= 0 or parameters_billions > 1000:
        return None
    return max(4 * GIB, int((parameters_billions * 0.8 + 2) * GIB))


def _ollama_disk_probe_path() -> Path:
    configured = os.environ.get("OLLAMA_MODELS")
    candidate = (
        Path(configured).expanduser()
        if configured
        else Path.home() / ".ollama" / "models"
    ).resolve()
    while not candidate.exists() and candidate.parent != candidate:
        candidate = candidate.parent
    return candidate


def pull_ollama_model(
    model: str,
    *,
    expected_size_gb: float | None = None,
) -> tuple[bool, str]:
    ollama = shutil.which("ollama")
    if ollama is None:
        return False, "Ollama is not installed"
    expected_size = (
        int(expected_size_gb * GIB)
        if (
            expected_size_gb is not None
            and math.isfinite(expected_size_gb)
            and expected_size_gb > 0
        )
        else estimate_ollama_download_size(model)
    )
    if expected_size is None or expected_size <= 0:
        return (
            False,
            "cannot safely estimate this model download; rerun `trade models pull` "
            "with --expected-size-gb",
        )
    assessment = assess_model_download(
        model=model,
        expected_size_bytes=expected_size,
        snapshot=resource_snapshot(_ollama_disk_probe_path()),
    )
    if assessment.status == "block":
        return (
            False,
            f"download blocked before network transfer: {assessment.reason}; "
            f"{assessment.snapshot.disk_free_bytes / GIB:.1f} GiB free, "
            f"{assessment.estimated_runtime_bytes / GIB:.1f} GiB required",
        )
    result = subprocess.run(  # noqa: S603
        [ollama, "pull", model],
        check=False,
        text=True,
        timeout=1800,
    )
    return (
        result.returncode == 0,
        f"disk preflight passed; ollama pull exited with status {result.returncode}",
    )


def _ollama_ready(base_url: str) -> bool:
    try:
        with httpx.Client(timeout=1.0, trust_env=False) as client:
            response = client.get(f"{base_url.rstrip('/')}/api/tags")
            return response.is_success
    except httpx.HTTPError:
        return False


def _database_ready(engine: Engine) -> bool:
    try:
        with engine.connect():
            return True
    except Exception:
        return False


def ensure_local_services(settings: Settings, engine: Engine) -> tuple[str, ...]:
    if not settings.local_service_autostart:
        return ()

    messages: list[str] = []
    database_host = urlparse(settings.database_url.replace("+psycopg", "")).hostname
    if database_host in {"localhost", "127.0.0.1", "::1"} and not _database_ready(engine):
        ok, detail = start_local_service(
            "postgresql",
            postgres_service_name=settings.postgres_service_name,
        )
        messages.append(
            f"PostgreSQL {'start requested' if ok else 'could not start'}: {detail}"
        )

    if settings.model_provider == "ollama" and not _ollama_ready(settings.ollama_base_url):
        ok, detail = start_local_service("ollama")
        messages.append(f"Ollama {'start requested' if ok else 'could not start'}: {detail}")

    if messages:
        for _ in range(20):
            database_ok = database_host not in {"localhost", "127.0.0.1", "::1"} or _database_ready(
                engine
            )
            ollama_ok = settings.model_provider != "ollama" or _ollama_ready(
                settings.ollama_base_url
            )
            if database_ok and ollama_ok:
                break
            time.sleep(0.25)
    return tuple(messages)


def shell_path_hint(launcher: Path) -> str | None:
    directory = str(launcher.parent)
    path_entries = os.environ.get("PATH", "").split(os.pathsep)
    if directory in path_entries:
        return None
    if operating_system() == "windows":
        return (
            f"Add `{directory}` to your user PATH in Windows Environment Variables, "
            "then open a new terminal."
        )
    shell_file = "~/.zprofile" if sys.platform == "darwin" else "~/.profile"
    return f'Add `export PATH="$HOME/.local/bin:$PATH"` to {shell_file}, then reopen Terminal.'
